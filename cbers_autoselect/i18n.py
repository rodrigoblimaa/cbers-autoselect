def normalized_language(locale):
    """Return a supported language code; default to English."""
    locale = str(locale or "").replace("-", "_").lower()
    return "pt_BR" if locale.startswith("pt") else "en"


class Localizer:
    """Immutable locale-specific message formatter; safe to share with tasks."""

    def __init__(self, locale):
        self.language = normalized_language(locale)

    def __call__(self, key, **kwargs):
        message = STRINGS[self.language].get(key, STRINGS["en"].get(key, key))
        return message.format(**kwargs)
